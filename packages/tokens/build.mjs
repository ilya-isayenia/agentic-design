// Builds the DTCG sources into CSS variables and a resolved JSON per theme.
//   build/tokens.css   :root { core scales } + one block per [data-brand][data-mode]
//   build/themes.json  { "pulse/dark": { "bg": "#000000", ... }, ... } for tools/contrast
import StyleDictionary from 'style-dictionary';
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, 'src');
const out = join(here, 'build');
const prefix = 'ds';
export const DEFAULT_THEME = { brand: 'pulse', mode: 'dark' };

const themes = readdirSync(join(src, 'brands')).flatMap((brand) =>
  readdirSync(join(src, 'brands', brand)).map((file) => ({ brand, mode: file.replace('.json', '') })),
);

/** @param {string[]} source @param {(token: any) => boolean} filter */
async function resolve(source, filter) {
  const sd = new StyleDictionary({
    source,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: { css: { transformGroup: 'css', prefix } },
  });
  const { allTokens } = await sd.getPlatformTokens('css');
  return allTokens.filter(filter);
}

const isPalette = (/** @type {any} */ t) => t.path[0] === 'palette';
const isThemed = (/** @type {any} */ t) => t.path[0] === 'color' || t.path[0] === 'component';
const block = (/** @type {string} */ selector, /** @type {any[]} */ tokens) =>
  `${selector} {\n${tokens.map((t) => `  --${t.name}: ${t.$value};`).join('\n')}\n}\n`;

const core = await resolve([join(src, 'core.json')], (t) => !isPalette(t));
let css = `/* Generated by packages/tokens/build.mjs from src/. Do not edit. */\n\n${block(':root', core)}`;
/** @type {Record<string, Record<string, string>>} */
const resolved = {};

for (const { brand, mode } of themes) {
  const tokens = await resolve([join(src, 'core.json'), join(src, 'brands', brand, `${mode}.json`)], isThemed);
  const isDefault = brand === DEFAULT_THEME.brand && mode === DEFAULT_THEME.mode;
  const selector = `${isDefault ? ':root,\n' : ''}[data-brand="${brand}"][data-mode="${mode}"]`;
  css += `\n${block(selector, tokens)}`;
  resolved[`${brand}/${mode}`] = Object.fromEntries(tokens.map((t) => [t.path.slice(1).join('-'), t.$value]));
}

mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'tokens.css'), css);
writeFileSync(join(out, 'themes.json'), JSON.stringify(resolved, null, 2) + '\n');
console.log(`tokens: ${themes.length} themes → build/tokens.css, build/themes.json`);
